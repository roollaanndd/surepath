// Load SurePath logo from /logo-full.png as data URL for embedding in jsPDF.
async function loadLogoAsDataUrl(overrideUrl?: string): Promise<string | null> {
  let url = overrideUrl;
  if (!url && typeof localStorage !== 'undefined') {
    const custom = localStorage.getItem('surepath_custom_logo');
    if (custom) url = custom;
  }
  if (!url) url = '/logo-full.png';
  return loadImageAsDataUrl(url);
}

// Fetch any image URL and return a JPEG data URL (white background applied to
// transparency — jsPDF addImage is more reliable with JPEG than PNG RGBA).
async function loadImageAsDataUrl(url: string): Promise<string | null> {
  if (typeof fetch === 'undefined') return null;
  try {
    if (url.startsWith('data:')) return url;
    const res = await fetch(url, { cache: 'force-cache' });
    if (!res.ok) return null;
    const blob = await res.blob();

    const rawDataUrl = await new Promise<string>((resolve, reject) => {
      const reader = new FileReader();
      reader.onload = () => resolve(reader.result as string);
      reader.onerror = reject;
      reader.readAsDataURL(blob);
    });

    if (typeof document === 'undefined') return rawDataUrl;
    try {
      const img = await loadImage(rawDataUrl);
      const targetW = Math.min(480, img.width || 480);
      const targetH = Math.round((img.height || 144) * (targetW / (img.width || targetW)));
      const canvas = document.createElement('canvas');
      canvas.width = targetW;
      canvas.height = targetH;
      const c2d = canvas.getContext('2d');
      if (!c2d) throw new Error('Canvas 2D context not available');
      c2d.fillStyle = '#FFFFFF';
      c2d.fillRect(0, 0, targetW, targetH);
      c2d.drawImage(img, 0, 0, targetW, targetH);
      return canvas.toDataURL('image/jpeg', 0.92);
    } catch {
      return rawDataUrl;
    }
  } catch {
    return null;
  }
}

function loadImage(src: string): Promise<HTMLImageElement> {
  return new Promise((resolve, reject) => {
    const img = new Image();
    img.onload = () => resolve(img);
    img.onerror = (e) => reject(e);
    img.src = src;
  });
}

function drawPolygon(doc: any, points: number[][], fill: boolean, stroke: boolean) {
  if (points.length < 3) return;
  const [x0, y0] = points[0];
  doc.lines(
    points.slice(1).map(([x, y], i) => [x - points[i][0], y - points[i][1]]),
    x0, y0, [1, 1], fill ? (stroke ? 'FD' : 'F') : 'S', true
  );
}

