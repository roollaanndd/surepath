// ─── Page geometry (US Letter) ──────────────────────────────────────────────
const PAGE_W = 612;   // 8.5in
const PAGE_H = 792;   // 11in
const MARGIN = 40;
const CONTENT_W = PAGE_W - 2 * MARGIN;

// ─── Data interface ────────────────────────────────────────────────────────
export type QuotationProductType = 'MOTOR' | 'PA' | 'PROPERTY' | 'TRAVEL' | 'HEALTH' | 'OTHER';

export interface QuotationObjectField {
  label: string;
  value: string;
  mono?: boolean;
}

export interface QuotationSlipData {
  // Quotation metadata
  quotationNumber: string;        // e.g. "QS/SP/2026/VII/0092"
  slipType?: string;              // e.g. "PENUTUPAN ASURANSI" / "RENEWAL 2026/2027"
  issueDate: string;              // e.g. "09 Juli 2026"
  yearTag?: string;               // e.g. "2026" (auto-extracted if missing)
  validUntil?: string;            // ISO date the offer expires (e-quotation)

  // Product (generic — motor, personal accident, property, travel, health, …)
  productType?: QuotationProductType;   // default 'MOTOR'
  productName?: string;                 // e.g. "Asuransi Kecelakaan Diri (Personal Accident)"
  objectSectionTitle?: string;          // default derived from productType
  objectDetails?: QuotationObjectField[]; // generic object rows; falls back to vehicle fields
  objectSummary?: string;               // one-liner used on the e-quotation page

  // Parties
  preparedForCompany: string;     // Customer / company name
  preparedForPerson: string;      // Customer contact person
  previousPolicyNumber?: string;  // For renewals
  insurer: string;                // Full insurer name
  insurerShort: string;           // e.g. "Zurich"
  insurerLogoUrl?: string;        // insurer brand logo (URL or data URL)

  // Agent (when the quotation is generated by/for an agent)
  agentName?: string;
  agentPhone?: string;
  agentCode?: string;

  // Period
  periodStart: string;            // e.g. "17 Juli 2026"
  periodEnd: string;              // e.g. "17 Juli 2027"
  periodStartShort?: string;      // e.g. "17 Jul 2026"
  periodEndShort?: string;

  // Cover page text
  titleMain?: string;             // default "Penawaran"
  titleMid?: string;              // default "Asuransi"
  titleAccent?: string;           // default "Anda."
  ledeHtml?: string;              // Lede paragraph (HTML stripped, plain text used)

  // Insured & object (legacy vehicle fields — used when objectDetails absent)
  insuredName: string;
  insuredAddress: string;
  vehicleBrand?: string;
  vehicleType?: string;
  vehicleYear?: string;
  engineNumber?: string;
  chassisNumber?: string;
  plateNumber?: string;
  seats?: string;
  color?: string;
  usage?: string;

  // Coverage
  coverageCondition: string;
  additionalCoverage: string;
  deductible: string;
  klausulList: string[];          // up to 3 strings rendered as Klausul chips

  // Sum insured table
  sumInsuredItems: { no: string; desc: string; amount: string }[];
  totalSumInsured: string;
  currency?: string;              // default "IDR"

  // Premium calculation
  premiumComponents: { component: string; basis: string; rate: string; premium: string }[];
  subtotalPremium: string;
  discountLabel: string;          // e.g. "Diskon Perpanjangan 25%"
  discountAmount: string;         // e.g. "(1.492.000,00)"
  premiumAfterDiscount: string;
  policyFee: string;
  stampDuty: string;
  totalPremium: string;

  // Lists
  subjectivityList: string[];
  termsList: string[];

  // Payment page
  closingTitle?: string;          // default "Lanjutkan Proteksi Anda,"
  closingAccent?: string;         // default "Tanpa Jeda."
  closingDesc?: string;
  bankName: string;               // e.g. "BANK BCA"
  bankNameShort?: string;         // e.g. "BCA"
  bankAccount: string;            // e.g. "5730 - 807 - 807"
  bankAccountName: string;
  paymentDueDate: string;
  transferMemo: string;

  // E-quotation link (QR target). Set by quotationService before generating.
  eQuoteCode?: string;
  eQuoteUrl?: string;             // e.g. https://myinsurepath.com/q/ab12cd34ef56

  // Optional logo override (data URL or URL string)
  logoUrl?: string;
}

// ─── Helpers ───────────────────────────────────────────────────────────────
const stripHtml = (s: string): string =>
  (s ?? '').replace(/<[^>]+>/g, '').replace(/&[a-z]+;/g, ' ').trim();

const fmtIDRShort = (s: string): string =>
  (s ?? '').replace(/^IDR\s*/i, '').replace(/[()]/g, '').trim();

// Human-readable link shown next to the QR ("myinsurepath.com/q/xxxx")
const humanUrl = (url: string): string => url.replace(/^https?:\/\//i, '');

const OBJECT_SECTION_TITLES: Record<QuotationProductType, string> = {
  MOTOR:    '// OBJEK PERTANGGUNGAN — KENDARAAN',
  PA:       '// OBJEK PERTANGGUNGAN — TERTANGGUNG',
  PROPERTY: '// OBJEK PERTANGGUNGAN — PROPERTI',
  TRAVEL:   '// OBJEK PERTANGGUNGAN — PERJALANAN',
  HEALTH:   '// OBJEK PERTANGGUNGAN — PESERTA',
  OTHER:    '// OBJEK PERTANGGUNGAN',
};

// Build generic object rows from legacy vehicle fields when the caller did
// not pass objectDetails (backwards compatibility with existing adapters).
function resolveObjectDetails(d: QuotationSlipData): QuotationObjectField[] {
  if (d.objectDetails && d.objectDetails.length > 0) return d.objectDetails;
  return [
    { label: 'MERK / TIPE / TAHUN', value: `${d.vehicleBrand ?? '-'} / ${d.vehicleType ?? '-'} / ${d.vehicleYear ?? '-'}` },
    { label: 'NO. MESIN', value: d.engineNumber ?? '-', mono: true },
    { label: 'NO. RANGKA', value: d.chassisNumber ?? '-', mono: true },
    { label: 'NOMOR POLISI', value: d.plateNumber ?? '-', mono: true },
    { label: 'TEMPAT DUDUK / WARNA', value: `${d.seats ?? '-'} · ${d.color ?? '-'}` },
    { label: 'PENGGUNAAN', value: d.usage ?? '-' },
  ];
}

// The mandatory disclaimer that must appear on the document: a quotation is
// an offer, never a confirmation — binding acceptance rests with the insurer.
const NOT_CONFIRMATION_ID = 'Dokumen ini adalah penawaran (quotation), BUKAN surat konfirmasi penutupan asuransi. Seluruh konfirmasi, akseptasi, dan penerbitan polis merupakan kewenangan penuh perusahaan asuransi (Penanggung).';

// ─── QR code generation ─────────────────────────────────────────────────────
async function makeQrDataUrl(text: string, dark: string, light: string): Promise<string | null> {
  try {
    const QRCode = (await import('qrcode')).default;
    return await QRCode.toDataURL(text, {
      errorCorrectionLevel: 'M',
      margin: 0,
      width: 480,
      color: { dark, light },
    });
  } catch (e) {
    console.warn('QuotationSlip: QR generation failed', e);
    return null;
  }
}

// ─── Main generator ────────────────────────────────────────────────────────
export async function generateQuotationSlipPDF(data: QuotationSlipData): Promise<void> {
  const jsPDF = await getJsPDF();
  const doc = new jsPDF({ orientation: 'portrait', unit: 'pt', format: 'letter' });

  // ─── Pre-load assets ────────────────────────────────────────────────────
  let logoDataUrl: string | null = null;
  try {
    logoDataUrl = await loadLogoAsDataUrl(data.logoUrl);
  } catch (e) {
    console.warn('QuotationSlip: logo load failed, falling back to drawn shield', e);
  }

  let insurerLogoDataUrl: string | null = null;
  if (data.insurerLogoUrl) {
    try {
      insurerLogoDataUrl = await loadImageAsDataUrl(data.insurerLogoUrl);
    } catch { /* insurer logo is decorative — never blocks generation */ }
  }

  // Unique QR — dark ink on white so any scanner reads it. NEVER fall back to
  // the bare homepage while a code exists: 1 quotation = 1 unique QR link.
  const eQuoteUrl = data.eQuoteUrl
    || (data.eQuoteCode ? `https://myinsurepath.com/q/${data.eQuoteCode}` : 'https://myinsurepath.com');
  const qrDataUrl = await makeQrDataUrl(eQuoteUrl, '#0E2A1C', '#FFFFFF');

  // Auto-extract year tag from quotation number if missing
  const yearTag = data.yearTag || (() => {
    const m = (data.quotationNumber || '').match(/\/(\d{4})\//);
    return m ? m[1] : String(new Date().getFullYear());
  })();

  // Defaults
  const productType: QuotationProductType = data.productType ?? 'MOTOR';
  const titleMain = data.titleMain || 'Penawaran';
  const titleMid = data.titleMid || 'Asuransi';
  const titleAccent = data.titleAccent || 'Anda.';
  const slipType = data.slipType || 'PENUTUPAN ASURANSI';
  const currency = data.currency || 'IDR';
  const closingTitle = data.closingTitle || 'Lanjutkan Proteksi Anda,';
  const closingAccent = data.closingAccent || 'Tanpa Jeda.';
  const closingDesc = data.closingDesc ||
    `Konfirmasi penawaran dan lakukan pembayaran sebelum ${data.periodStart} agar perlindungan berjalan tanpa terputus.`;
  const periodStartShort = data.periodStartShort || data.periodStart;
  const periodEndShort = data.periodEndShort || data.periodEnd;
  const bankNameShort = data.bankNameShort || data.bankName;
  const totalPremiumClean = fmtIDRShort(data.totalPremium);
  const discountAmountClean = fmtIDRShort(data.discountAmount);

  const ctxShared = {
    yearTag, titleMain, titleMid, titleAccent, slipType, currency,
    closingTitle, closingAccent, closingDesc,
    periodStartShort, periodEndShort, bankNameShort,
    totalPremiumClean, discountAmountClean,
    logoDataUrl, insurerLogoDataUrl, qrDataUrl, eQuoteUrl, productType,
  };

  drawCoverPage(doc, data, ctxShared);
  doc.addPage();
  drawDataPage(doc, data, ctxShared);
  doc.addPage();
  drawPremiPage(doc, data, ctxShared);
  doc.addPage();
  drawPaymentPage(doc, data, ctxShared);

  // ─── Metadata ───────────────────────────────────────────────────────────
  doc.setProperties({
    title: `${data.quotationNumber} — Penawaran Asuransi`,
    subject: `Quotation Slip — ${data.insurerShort}`,
    author: 'SurePath · PT. Ruang Proteksi Indonesia',
    creator: 'SurePath Digital Insurance Platform',
    keywords: 'SurePath, Quotation, Asuransi, ' + data.quotationNumber,
  });

  const filename = `${data.quotationNumber.replace(/[/\s]/g, '_')}_Penawaran_${data.insurerShort}_${data.preparedForCompany.replace(/[^a-zA-Z0-9]/g, '').slice(0, 20)}.pdf`;
  doc.save(filename);
}

// ═══════════════════════════════════════════════════════════════════════════
// PAGE 1 — COVER (dark green)
// ═══════════════════════════════════════════════════════════════════════════
function drawCoverPage(doc: any, d: QuotationSlipData, ctx: any) {
  const { yearTag, titleMain, titleMid, titleAccent, slipType, logoDataUrl, qrDataUrl, eQuoteUrl } = ctx;

  // Clean white cover with subtle green decorative accents
  doc.setFillColor(...COLOR.darkBg);
  doc.rect(0, 0, PAGE_W, PAGE_H, 'F');
  doc.setFillColor(243, 250, 245);
  doc.circle(PAGE_W - 50, 210, 130, 'F');
  doc.setFillColor(232, 244, 235);
  doc.circle(70, PAGE_H - 180, 95, 'F');

  // ─── Top row: logo + quotation stamp ──────────────────────────────────
  drawSurePathLogo(doc, MARGIN, MARGIN + 6, 'dark', logoDataUrl);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(7);
  doc.setTextColor(...COLOR.emeraldDeep);
  doc.text('QUOTATION SLIP', PAGE_W - MARGIN, MARGIN + 2, { align: 'right' });
  doc.setFontSize(9);
  doc.setFont('helvetica', 'bold');
  doc.text(d.quotationNumber, PAGE_W - MARGIN, MARGIN + 14, { align: 'right' });

  // ─── Doc class label ──────────────────────────────────────────────────
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(8.5);
  doc.setTextColor(...COLOR.emeraldDeep);
  doc.text(`// QUOTATION SLIP — ${slipType}`, MARGIN, MARGIN + 62);

  // ─── Title block ──────────────────────────────────────────────────────
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(...COLOR.ink);
  doc.setFontSize(40);
  doc.text(titleMain, MARGIN, 168);
  doc.text(titleMid, MARGIN, 212);
  doc.setTextColor(...COLOR.emeraldBright);
  doc.text(titleAccent, MARGIN + doc.getTextWidth(titleMid + ' '), 212);

  // Lede paragraph
  const lede = stripHtml(d.ledeHtml || '');
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9.5);
  doc.setTextColor(...COLOR.inkMuted);
  const ledeLines = doc.splitTextToSize(lede, CONTENT_W).slice(0, 3);
  doc.text(ledeLines, MARGIN, 242);

  // ─── Meta grid (3 rows × 2 cols) ──────────────────────────────────────
  const boxY = 300;
  const boxH = 216;
  const rowH = boxH / 3;
  const colW = CONTENT_W / 2;

  doc.setDrawColor(...COLOR.borderMuted);
  doc.setLineWidth(0.8);
  doc.roundedRect(MARGIN, boxY, CONTENT_W, boxH, 12, 12, 'S');
  for (let i = 1; i < 3; i++) doc.line(MARGIN, boxY + i * rowH, MARGIN + CONTENT_W, boxY + i * rowH);
  doc.line(MARGIN + colW, boxY, MARGIN + colW, boxY + boxH);

  const productLabel = d.productName || (ctx.productType === 'MOTOR' ? 'Asuransi Kendaraan Bermotor' : 'Produk Asuransi');
  const cells = [
    { label: 'NOMOR PENAWARAN',    value: d.quotationNumber, accent: true, mono: true },
    { label: 'TANGGAL PENERBITAN', value: d.issueDate },
    { label: 'DISIAPKAN UNTUK',    value: d.preparedForCompany, sub: d.preparedForPerson },
    { label: 'PRODUK',             value: productLabel, accent: true },
    { label: 'PENANGGUNG',         value: d.insurer },
    { label: 'PERIODE ASURANSI',   value: `${d.periodStart} — ${d.periodEnd}` },
  ];

  cells.forEach((c, i) => {
    const col = i % 2;
    const row = Math.floor(i / 2);
    const cx = MARGIN + col * colW + 14;
    const cy = boxY + row * rowH + 20;

    doc.setFont('helvetica', 'bold');
    doc.setFontSize(6.5);
    doc.setTextColor(...COLOR.inkMuted);
    doc.text(c.label, cx, cy);

    doc.setFont(c.mono ? 'courier' : 'helvetica', 'bold');
    doc.setFontSize(10);
    doc.setTextColor(...(c.accent ? COLOR.emerald : COLOR.ink));
    const vLines = doc.splitTextToSize(c.value, colW - 28).slice(0, 2);
    doc.text(vLines, cx, cy + 15);

    if (c.sub) {
      doc.setFont('helvetica', 'normal');
      doc.setFontSize(8.5);
      doc.setTextColor(...COLOR.inkMuted);
      doc.text(String(c.sub), cx, cy + 15 + vLines.length * 12);
    }
  });

  // ─── Bottom cards: QR e-quotation (left) + agent / contact (right) ─────
  const cardY = boxY + boxH + 18;
  const cardH = 138;
  const qrCardW = 150;

  // QR card (white so the QR scans reliably)
  doc.setFillColor(...COLOR.white);
  doc.roundedRect(MARGIN, cardY, qrCardW, cardH, 10, 10, 'F');
  if (qrDataUrl) {
    doc.addImage(qrDataUrl, 'PNG', MARGIN + (qrCardW - 88) / 2, cardY + 10, 88, 88, undefined, 'FAST');
  }
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(7);
  doc.setTextColor(...COLOR.emeraldDeep);
  doc.text('SCAN — E-QUOTATION', MARGIN + qrCardW / 2, cardY + 110, { align: 'center' });
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(6.3);
  doc.setTextColor(...COLOR.inkMuted);
  doc.text('Lihat, konfirmasi & bayar online', MARGIN + qrCardW / 2, cardY + 120, { align: 'center' });
  doc.setFont('courier', 'bold');
  doc.setFontSize(6.3);
  doc.setTextColor(...COLOR.emeraldDeep);
  doc.text(humanUrl(eQuoteUrl), MARGIN + qrCardW / 2, cardY + 129, { align: 'center' });

  // Agent / prepared-by card
  const agX = MARGIN + qrCardW + 12;
  const agW = CONTENT_W - qrCardW - 12;
  doc.setFillColor(...COLOR.darkBgMid);
  doc.setDrawColor(...COLOR.borderMuted);
  doc.setLineWidth(0.6);
  doc.roundedRect(agX, cardY, agW, cardH, 10, 10, 'FD');

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(7);
  doc.setTextColor(...COLOR.emerald);
  doc.text('DISIAPKAN OLEH', agX + 16, cardY + 20);

  if (d.agentName) {
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(13);
    doc.setTextColor(...COLOR.ink);
    doc.text(d.agentName, agX + 16, cardY + 40);
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(8.5);
    doc.setTextColor(...COLOR.inkMuted);
    doc.text(`Agen Resmi SurePath${d.agentCode ? ` · ${d.agentCode}` : ''}`, agX + 16, cardY + 54);
    if (d.agentPhone) {
      doc.setFont('courier', 'bold');
      doc.setFontSize(10);
      doc.setTextColor(...COLOR.emeraldDeep);
      doc.text(d.agentPhone, agX + 16, cardY + 70);
    }
  } else {
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(13);
    doc.setTextColor(...COLOR.ink);
    doc.text('Tim SurePath', agX + 16, cardY + 40);
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(8.5);
    doc.setTextColor(...COLOR.inkMuted);
    doc.text('PT. Ruang Proteksi Indonesia', agX + 16, cardY + 54);
    doc.setFont('courier', 'bold');
    doc.setFontSize(10);
    doc.setTextColor(...COLOR.emerald);
    doc.text('halo@myinsurepath.com', agX + 16, cardY + 70);
  }

  // Divider + validity inside agent card
  doc.setDrawColor(...COLOR.borderMuted);
  doc.setLineWidth(0.5);
  doc.line(agX + 16, cardY + 84, agX + agW - 16, cardY + 84);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(6.5);
  doc.setTextColor(...COLOR.inkMuted);
  doc.text('MASA BERLAKU PENAWARAN', agX + 16, cardY + 98);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8);
  doc.setTextColor(...COLOR.ink);
  const validityText = d.validUntil
    ? `Berlaku sampai ${d.validUntil} — konfirmasi sebelum tanggal tersebut.`
    : 'Berlaku 30 hari sejak tanggal penerbitan.';
  doc.text(doc.splitTextToSize(validityText, agW - 32), agX + 16, cardY + 110);

  // ─── Disclaimer line ────────────────────────────────────────────────────
  const discY = cardY + cardH + 18;
  doc.setFont('helvetica', 'italic');
  doc.setFontSize(7.2);
  doc.setTextColor(170, 190, 178);
  doc.text(doc.splitTextToSize(NOT_CONFIRMATION_ID, CONTENT_W), MARGIN, discY);

  // ─── Footer ─────────────────────────────────────────────────────────────
  const footerY = PAGE_H - 46;
  drawDottedFooterLine(doc, footerY, COLOR.borderMuted, COLOR.emerald);

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(9);
  doc.setTextColor(...COLOR.ink);
  doc.text('PT. Ruang Proteksi Indonesia', MARGIN, footerY + 13);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(7.5);
  doc.setTextColor(...COLOR.inkMuted);
  doc.text('SurePath — Digital Insurance Distribution Platform', MARGIN, footerY + 24);
  doc.setTextColor(...COLOR.emerald);
  doc.text('myinsurepath.com', MARGIN, footerY + 34);
  doc.setTextColor(170, 190, 178);
  doc.text(' · Bekerja sama dengan perusahaan asuransi berizin & diawasi OJK', MARGIN + doc.getTextWidth('myinsurepath.com'), footerY + 34);

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(8);
  doc.setTextColor(...COLOR.emerald);
  doc.text(`SUREPATH.QS.${yearTag}`, PAGE_W - MARGIN, footerY + 13, { align: 'right' });
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(7);
  doc.setTextColor(170, 190, 178);
  doc.text('Hal. 1 dari 4', PAGE_W - MARGIN, footerY + 24, { align: 'right' });
}

