export const CAR_BRANDS = Object.keys(VEHICLE_DATABASE).sort();

export function getModelsForBrand(brand: string): VehicleModel[] {
  return VEHICLE_DATABASE[brand]?.models ?? [];
}

export function getMarketValue(brand: string, model: string): number | null {
  const entry = VEHICLE_DATABASE[brand];
  if (!entry) return null;
  const m = entry.models.find(m => m.model === model);
  return m ? m.marketValueRp : null;
}