// Numbered list — returns consumed height; stops before maxY when given
function drawNumberedList(doc: any, x: number, y: number, w: number, items: string[], maxY = PAGE_H - 52): number {
  let cy = y + 10;
  items.forEach((item, i) => {
    const lines = doc.splitTextToSize(item, w - 20).slice(0, 3);
    const itemH = lines.length * 9 + 5;
    if (cy + itemH > maxY) return;

    doc.setFont('courier', 'bold');
    doc.setFontSize(7.5);
    doc.setTextColor(...COLOR.emeraldDeep);
    doc.text(`${i + 1}.`, x, cy);

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(7.5);
    doc.setTextColor(...COLOR.ink);
    doc.text(lines, x + 18, cy);
    cy += itemH;
  });
  return cy - y;
}

