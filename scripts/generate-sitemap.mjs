// Renders public/sitemap.xml from the route inventory in src/seo/seo.ts.
//
// The sitemap was maintained by hand, so it drifted: routes gained metadata in
// seo.ts without ever reaching the sitemap. Generating it means the two cannot
// disagree. Run via `npm run seo:sitemap`; `npm run build` runs it first.
import { writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, resolve } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
// pathToFileURL is mandatory on Windows: a bare `C:\…` absolute path is an
// invalid ESM specifier under Node ≥ 11 (ERR_UNSUPPORTED_ESM_URL_SCHEME).
const { SITE, indexablePaths } = await import(pathToFileURL(resolve(here, '../src/seo/seo.ts')).href);

const entries = indexablePaths();
const body = entries
  .map(e => `  <url>\n    <loc>${SITE.origin}${e.path}</loc>\n    <lastmod>${e.lastmod}</lastmod>\n  </url>`)
  .join('\n');

const xml = `<?xml version="1.0" encoding="UTF-8"?>
<!-- GENERATED by scripts/generate-sitemap.mjs from src/seo/seo.ts — do not edit by hand. -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${body}
</urlset>
`;

const out = resolve(here, '../public/sitemap.xml');
writeFileSync(out, xml);
console.log(`sitemap: ${entries.length} URLs → public/sitemap.xml`);
